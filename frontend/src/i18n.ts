function formatText(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  let result = template;
  for (const [name, value] of Object.entries(params)) {
    result = result.replaceAll(`{${name}}`, String(value));
  }
  return result;
}

export function setLocale(next: Locale): void {
  const normalized = normalizeLocale(next);
  localeRef.value = normalized;
  try {
    localStorage.setItem(STORAGE_KEY, normalized);
  } catch {
    // ignore storage errors
  }
}

export function applyBackendDefaultLocale(next: unknown): void {
  if (hasStoredLocale()) {
    return;
  }
  setLocale(normalizeLocale(next));
}

export function t(key: string, params?: Record<string, string | number>): string {
  const text = messages[localeRef.value][key] ?? messages.en[key] ?? key;
  return formatText(text, params);
}

export function useI18n() {
  const localeItems = computed(() => [
    { title: t("lang.english"), value: "en" },
    { title: t("lang.chinese"), value: "zh" },
  ]);
  const dateLocale = computed(() => (localeRef.value === "zh" ? "zh-CN" : "en-US"));

  return {
    locale: localeRef,
    setLocale,
    t,
    localeItems,
    dateLocale,
    supportedLocales: SUPPORTED_LOCALES,
    hasStoredLocalePreference: hasStoredLocale,
  };
}
